#!/usr/bin/env node
/**
 * HAMDI ITALIE — converts the Google Apps Script (HtmlService) frontend into a static
 * website for GitHub Pages.
 *
 *   node tools/convert.js <path to a hamdi_italia checkout>
 *
 * Reads  <hamdi_italia>/google-apps-script/frontend/{visitor,admin}/Index.html and the
 * partials they include (<?!= include_('...') ?>), then writes into this repository:
 *   index.html, admin/index.html        the two pages
 *   assets/css/*.css, assets/js/**.js   one file per partial (cache-busted with ?v=<hash>)
 * Only the frontend is read. The backend (*.gs) is never copied here: this repository
 * is public and the backend holds private IDs.
 *
 * Two changes are made to shared/Ui:
 *   1. api(): calls the Apps Script JSON API (assets/js/config.js → API_URL, served by
 *      apps-script/HttpApi.gs) instead of google.script.run.
 *   2. navigate(): pushes a history entry so the browser Back button works.
 * Each change checks that the original code is still there, so a later re-sync fails
 * loudly instead of silently producing a broken site.
 */
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const src = process.argv[2];
if (!src) { console.error('Usage: node tools/convert.js <path to hamdi_italia>'); process.exit(1); }
const GAS = path.resolve(src, 'google-apps-script');
const OUT = path.resolve(__dirname, '..');
if (!fs.existsSync(path.join(GAS, 'frontend/visitor/Index.html'))) {
  console.error('Not a hamdi_italia checkout: ' + GAS); process.exit(1);
}

function write(rel, content) {
  const p = path.join(OUT, rel);
  fs.mkdirSync(path.dirname(p), { recursive: true });
  fs.writeFileSync(p, content);
}
const hash = s => crypto.createHash('sha256').update(s).digest('hex').slice(0, 10);
const kebab = s => s.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();

function replaceOnce(text, from, to, what) {
  const n = text.split(from).length - 1;
  if (n !== 1) throw new Error('Patch "' + what + '": expected the original code once, found ' + n + ' times. Update tools/convert.js.');
  return text.replace(from, () => to);
}

/* ---- Patches for shared/Ui ------------------------------------------------------- */
const API_ORIGINAL = `    } else if (window.MOCK_API && (fn in MOCK_API)) {`;
const API_HTTP = `    } else if (window.HAMDI_CONFIG && HAMDI_CONFIG.API_URL) {
      // GitHub Pages: same api_* functions, reached through the Apps Script JSON API
      // (apps-script/HttpApi.gs). text/plain avoids a CORS preflight; Apps Script
      // answers with a redirect to googleusercontent.com, which allows any origin.
      fetch(HAMDI_CONFIG.API_URL, {
        method: 'POST',
        headers: { 'Content-Type': 'text/plain;charset=utf-8' },
        body: JSON.stringify({ fn: fn, args: args }),
        credentials: 'omit',
        redirect: 'follow'
      }).then(function (r) {
        if (!r.ok) throw new Error('INTERNAL: HTTP ' + r.status);
        return r.json();
      }).then(function (res) {
        if (res && res.ok === true) resolve(res.result);
        else reject(new Error(String((res && res.error) || 'INTERNAL: An error occurred.')));
      }).catch(function (err) {
        var msg = String((err && err.message) || err || '');
        // Network failure, or the API is not deployed yet (no CORS headers → TypeError).
        reject(new Error(/^[A-Z_]+: /.test(msg) ? msg : 'INTERNAL: ' + msg));
      });
` + API_ORIGINAL;
const NAV_ORIGINAL = `else if (location.hash !== hash) history.replaceState(null, '', hash);`;
const NAV_STATIC = `else if (location.hash !== hash) history.pushState(null, '', hash);`;

function patchUi(js) {
  js = replaceOnce(js, API_ORIGINAL, API_HTTP, 'api() over HTTP');
  js = replaceOnce(js, NAV_ORIGINAL, NAV_STATIC, 'history.pushState');
  return js;
}

/* ---- Partials → files ------------------------------------------------------------ */
const written = {};
function assetFor(partial) {
  if (written[partial]) return written[partial];
  const text = fs.readFileSync(path.join(GAS, partial + '.html'), 'utf8');
  const parts = partial.split('/');
  const name = kebab(parts[parts.length - 1]);
  const group = parts[0] === 'shared' ? '' : parts[1] + '/';
  const styles = [...text.matchAll(/<style>([\s\S]*?)<\/style>/g)].map(m => m[1]);
  const scripts = [...text.matchAll(/<script>([\s\S]*?)<\/script>/g)].map(m => m[1]);
  const rest = text.replace(/<style>[\s\S]*?<\/style>/g, '').replace(/<script>[\s\S]*?<\/script>/g, '').replace(/<!--[\s\S]*?-->/g, '').trim();
  if (rest) throw new Error(partial + ': unexpected markup outside <style>/<script>');
  const tags = [];
  if (styles.length) {
    const css = styles.join('\n').replace(/^\n/, '');
    const rel = 'assets/css/' + group + (name === 'styles' ? 'main' : name) + '.css';
    write(rel, '/* Generated by tools/convert.js from ' + partial + '.html — edit the source, not this file. */\n' + css);
    tags.push('<link rel="stylesheet" href="/' + rel + '?v=' + hash(css) + '">');
  }
  if (scripts.length) {
    let js = scripts.join('\n').replace(/^\n/, '');
    if (partial === 'shared/Ui') js = patchUi(js);
    const rel = 'assets/js/' + group + name + '.js';
    write(rel, '/* Generated by tools/convert.js from ' + partial + '.html — edit the source, not this file. */\n' + js);
    tags.push('<script src="/' + rel + '?v=' + hash(js) + '"></script>');
  }
  return (written[partial] = tags.join('\n  '));
}

/* ---- Pages ----------------------------------------------------------------------- */
const config = fs.readFileSync(path.join(OUT, 'assets/js/config.js'), 'utf8');
const CONFIG_TAG = '<script src="/assets/js/config.js?v=' + hash(config) + '"></script>';

const HEAD = {
  visitor: [
    '<title>HAMDI ITALIE</title>',
    '<meta name="description" content="دليلك الشامل للحياة والإجراءات الإدارية في إيطاليا — Votre guide complet pour vivre et effectuer vos démarches en Italie — Your complete guide to life in Italy.">',
    '<meta property="og:title" content="HAMDI ITALIE">',
    '<meta property="og:type" content="website">',
    '<meta name="theme-color" content="#E9EDF3">',
    '<link rel="icon" href="/assets/logo.svg" type="image/svg+xml">',
  ],
  admin: [
    '<title>HAMDI ITALIE — Admin</title>',
    '<meta name="robots" content="noindex, nofollow">',
    '<meta name="theme-color" content="#E9EDF3">',
    '<link rel="icon" href="/assets/logo.svg" type="image/svg+xml">',
  ],
};

function page(app, outRel) {
  let html = fs.readFileSync(path.join(GAS, 'frontend', app, 'Index.html'), 'utf8');
  let first = true;
  html = html.replace(/<\?!=\s*include_?\('([^']+)'\);?\s*\?>/g, (_, p) => {
    let tags = assetFor(p);
    if (first && tags.includes('<script')) { tags = CONFIG_TAG + '\n  ' + tags; first = false; }
    return tags;
  });
  if (/<\?/.test(html)) throw new Error(app + ': template code left in the page: ' + html.match(/<\?[\s\S]*?\?>/)[0]);
  if (first) throw new Error(app + ': no script found for config.js');
  html = html.replace(/<meta name="viewport"[^>]*>/, m => m + '\n  ' + HEAD[app].join('\n  '));
  html = '<!-- Generated by tools/convert.js from google-apps-script/frontend/' + app + '/Index.html -->\n' + html;
  write(outRel, html);
  console.log('wrote ' + outRel);
}

page('visitor', 'index.html');
page('admin', 'admin/index.html');
console.log('assets: ' + Object.keys(written).length + ' partials converted');
