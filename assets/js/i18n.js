var LANG_NAMES = { ar: 'العربية', fr: 'Français', en: 'English' };
var SUPPORTED_LANGS = ['ar', 'fr', 'en'];
var DEFAULT_LANG = 'ar';
var currentLang = DEFAULT_LANG;

function t(key) {
  return (I18N[currentLang] && I18N[currentLang][key]) || I18N.en[key] || key;
}

/** A record's text in the current language, else the first available among ar/fr/en. */
function tf(record, field) {
  if (!record) return '';
  if (record[field + '_' + currentLang]) return record[field + '_' + currentLang];
  for (var i = 0; i < SUPPORTED_LANGS.length; i++) if (record[field + '_' + SUPPORTED_LANGS[i]]) return record[field + '_' + SUPPORTED_LANGS[i]];
  return '';
}

function detectLang() {
  var saved = null;
  try { saved = localStorage.getItem('hi_lang'); } catch (e) {}
  if (saved && I18N[saved]) return saved;
  var nav = (navigator.language || '').slice(0, 2);
  return I18N[nav] ? nav : DEFAULT_LANG;
}

function setLang(lang) {
  if (!I18N[lang]) lang = DEFAULT_LANG;
  currentLang = lang;
  try { localStorage.setItem('hi_lang', lang); } catch (e) {}
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
  document.querySelectorAll('[data-i18n]').forEach(function (n) { n.textContent = t(n.getAttribute('data-i18n')); });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(function (n) { n.placeholder = t(n.getAttribute('data-i18n-placeholder')); });
  document.querySelectorAll('[data-i18n-aria]').forEach(function (n) { n.setAttribute('aria-label', t(n.getAttribute('data-i18n-aria'))); });
}
